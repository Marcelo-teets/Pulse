import assert from "node:assert/strict";
import { computeQuality, evidenceFlags, REVIEW_FIELDS } from "../lib/quality-core.js";
import { scoreCompany } from "../lib/dcm-fit.js";
import { csvCell,csvDocument } from "../lib/csv-safe.js";
assert.equal(computeQuality([]).homologated,false);
assert.equal(computeQuality([]).fields.full_name.precision,null);
const cases = Array.from({length:40},(_,i)=>({id:i+1,name:"Pessoa "+(i+1),title:i%2?"CFO":"CEO",company:"Empresa "+(i+1),location:i%2?"Brasil":"São Paulo",language:i%2?"EN":"PT"}));
const reviews = cases.flatMap(c=>["full_name","current_title","current_company","company_linkedin_url"].map(field=>({capture_id:c.id,field_key:field,verdict:"correct"})));
assert.equal(computeQuality(reviews).homologated,true);
assert.equal(computeQuality(reviews).profiles_reviewed,40);
const duplicates=[...reviews,{capture_id:500,profile_key:"https://www.linkedin.com/in/ana",field_key:"full_name",verdict:"correct"},{capture_id:501,profile_key:"https://www.linkedin.com/in/ana",field_key:"current_title",verdict:"correct"}];
assert.equal(computeQuality(duplicates).profiles_reviewed,41,"only one repeated profile counted");
const oneError=reviews.map((r,i)=>i===0?{...r,verdict:"incorrect"}:r);
assert.equal(computeQuality(oneError).fields.full_name.precision,97.5);
assert.equal(computeQuality(oneError).homologated,false);
assert.equal(computeQuality(reviews.filter(r=>r.field_key!=="current_company")).homologated,false);
assert.equal(computeQuality(reviews,29).homologated,false);
assert.equal(computeQuality(reviews,51).homologated,false);
assert.equal(REVIEW_FIELDS.length,10);
const flags=evidenceFlags({current_company:"A"},{company_name:"B"});
assert.ok(flags.flags.includes("company_identity_conflict"));
assert.ok(flags.evidence_score < 100);
assert.equal(scoreCompany({company_name:"Indústria de Móveis",description:"fabricação de móveis"}).fit,"sem_evidencia_suficiente");
const fit=scoreCompany({company_name:"Fintech",description:"crédito com antecipação de recebíveis",employee_count:"51-200 funcionários"});
assert.ok(fit.score>=60);
assert.equal(fit.fit,"potencial_alto");
assert.equal(scoreCompany({company_name:"Startup Tech"}).score,0);
assert.ok(csvCell("=HYPERLINK(\"bad\")").startsWith("\"'="));
assert.ok(csvDocument(["a"],[["+evil"]]).startsWith("\uFEFF"));
console.log("Pulse Quality/DCF intelligence: 40 synthetic test records; human precision NOT measured.");
